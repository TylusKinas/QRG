test('conditions: count, chance, key, pos (this / kind), code', () => {
  const run = (cond, setup) => {
    const P = one({ t: 'always' }, [cond], [{ t: 'setvar', v: 'score', vop: '=', n: '1' }]);
    const g = launch(P, 1);
    if (setup) setup(g);
    g.frame(2);
    return g.dbg().score;
  };
  assert.equal(run({ t: 'count', k: 'k2', op: '==', n: '1' }), 1);
  assert.equal(run({ t: 'count', k: 'k2', op: '>', n: '1' }), 0);
  assert.equal(run({ t: 'chance', n: '100' }), 1);
  assert.equal(run({ t: 'chance', n: '0' }), 0);
  assert.equal(run({ t: 'key', btn: 'a' }), 0);
  assert.equal(run({ t: 'key', btn: 'a' }, g => { g.I.a = 1; }), 1);
  assert.equal(run({ t: 'pos', w: 'k1', axis: 'x', op: '<', n: '120' }), 1);
  assert.equal(run({ t: 'pos', w: 'k1', axis: 'y', op: '>', n: '120' }), 0);
  assert.equal(run({ t: 'code', js: 'level == 5 && 2 > 1' }), 1);
  assert.equal(run({ t: 'code', js: 'false' }), 0);
});

