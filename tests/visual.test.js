test('bouncing ball: reflects off walls, the paddle keeps it alive, missing costs a life', () => {
  const g = launch(tpl('Bouncing ball'), 2);
  const ball = actors(g, 'k2')[0], paddle = actors(g, 'k1')[0];
  assert.ok(ball && paddle);
  g.I.t = 1;
  for (let n = 0; n < 900; n++) { g.I.x = ball.x + 4; g.I.y = 100; g.frame(1); }
  assert.equal(g.dbg().lives, 3, 'paddle followed the ball');
  assert.ok(g.dbg().score >= 5, 'score ' + g.dbg().score);
  assert.ok(ball.x >= 0 && ball.x <= 256 && ball.y >= 0 && ball.y <= 240);
  g.I.t = 0;
  const lives = g.dbg().lives;
  paddle.x = 0; ball.x = 200; ball.y = 100; ball.vx = 0; ball.vy = 3;          // the ball falls where the paddle is not
  for (let n = 0; n < 80 && g.dbg().lives === lives; n++) g.frame(1);
  assert.equal(g.dbg().lives, lives - 1, 'a missed ball costs a life');
  assert.deepEqual([ball.x, ball.y, ball.vx, ball.vy], [126, 63, 2, 3], 'the ball was served again (and moved one step)');
});

