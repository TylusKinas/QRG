test('variable names: unsafe or reserved names are rejected and vsafeName repairs them', () => {
  const P = base();
  P.vars.push({ n: 'r', v: 0, show: 0 }, { n: '9lives', v: 0, show: 0 }, { n: 'ok_name', v: 0, show: 0 });
  assert.equal(api.vcompile(P).errors.length, 2);
  for (const bad of ['r', 'i', 'a', 'over', 'init', 'class', 'cls', 'RED', '9x', 'a b', '', 'léon']) {
    const s = api.vsafeName(bad);
    assert.match(s, /^[A-Za-z_][A-Za-z0-9_]*$/, bad);
    assert.ok(!api.LIBNAMES.includes(s) && !['i', 'a', 'b', 'q', 'over', 'init', 'class'].includes(s), bad + ' -> ' + s);
  }
  assert.equal(api.vsafeName('score'), 'score');
});

