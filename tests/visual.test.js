test('vsanitize rejects non-projects and bounds hostile input', () => {
  for (const bad of [null, 5, 'x', [], {}, { kinds: 1, objs: [], vars: [], rules: [] }]) assert.equal(api.vsanitize(bad), null);
  const hostile = {
    bg: 999, kinds: Array.from({ length: 500 }, (_, i) => ({ id: 'k' + i, name: 'x'.repeat(5000), spr: [999, -5, 'a'], c: 99, z: 1e9 })),
    objs: Array.from({ length: 5000 }, () => ({ k: 'k1', x: 1e12, y: NaN })),
    vars: Array.from({ length: 500 }, (_, i) => ({ n: 'v' + i, v: 'zz' })),
    rules: Array.from({ length: 5000 }, () => ({ when: { t: 'always', evil: 'y'.repeat(9999) }, ifs: Array(99).fill({ t: 'chance', n: 5 }), dos: [{ t: 'nope' }, { t: 'sound', n: '1' }] }))
  };
  const P = api.vsanitize(hostile);
  assert.ok(P.kinds.length <= 32 && P.objs.length <= 300 && P.vars.length <= 16 && P.rules.length <= 100);
  assert.ok(P.kinds.every(k => k.name.length <= 20 && k.spr.length === 8 && k.spr.every(b => b >= 0 && b <= 255) && k.c <= 15 && k.z <= 8));
  assert.ok(P.objs.every(o => Math.abs(o.x) <= 320 && Number.isFinite(o.y)));
  assert.ok(P.rules.every(r => r.ifs.length <= 12 && r.dos.length === 1 && r.when.evil.length <= 400));
  assert.equal(api.vsanitize({ kinds: [{ id: 'a' }, { id: 'a' }], objs: [], vars: [], rules: [] }), null, 'duplicate ids');
});
