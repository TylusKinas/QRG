test('coin catcher: catching coins scores, skulls cost lives, game over and restart', () => {
  const g = launch(tpl('Coin catcher'), 3);
  assert.equal(g.dbg().lives, 3);
  g.frame(60);                                               // a coin appears after 0.7 s
  assert.ok(actors(g, 'k2').length >= 1);
  const player = actors(g, 'k1')[0], coin = actors(g, 'k2')[0];
  coin.x = player.x; coin.y = player.y;
  g.frame(1);
  assert.equal(g.dbg().score, 1);
  assert.equal(coin.on, 0);
  g.L.add(g.dbg().k.k3, player.x, player.y);
  g.frame(1);
  assert.equal(g.dbg().lives, 2);
  g.f.set('lives', 0);
  g.frame(2);
  assert.equal(g.dbg().over, 'GAME OVER');
  assert.ok(g.texts.includes('GAME OVER'));
  g.frame(5);
  assert.equal(g.dbg().over, 'GAME OVER', 'stays over until tapped');
  g.I.C = 1; g.frame(1);
  assert.equal(g.dbg().over, '');
  assert.equal(g.dbg().lives, 3);
  assert.equal(g.dbg().score, 0);
  assert.equal(actors(g, 'k1').length, 1, 'player was re-created, nothing else left');
  assert.equal(actors(g, 'k2').length, 0);
});

