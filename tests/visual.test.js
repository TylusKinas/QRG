/* Tests for the visual editor compiler: every block type compiles, templates play correctly. */
const test = require('node:test');
const assert = require('node:assert/strict');
const { loadCore, makeEnv, compileGame } = require('./helpers/load.js');

const api = loadCore();
const clone = o => JSON.parse(JSON.stringify(o));
const tpl = n => clone(api.VTEMPLATES.find(t => t.name === n).p);

/* Compile a project in debug mode and return a running game with helpers. */
function launch(P, seed) {
  const { code, errors } = api.vcompile(P, { debug: true });
  assert.deepEqual(Array.from(errors), [], 'compile errors:\n' + Array.from(errors).join('\n') + '\n' + code);
  const env = makeEnv(api);
  if (seed != null) env.L.seed(seed);
  const texts = [], sounds = [];
  const t0 = env.L.t, tc0 = env.L.tc, s0 = env.L.s;
  env.L.t = (s, ...r) => { texts.push(String(s)); return t0(s, ...r); };
  env.L.tc = (s, ...r) => { texts.push(String(s)); return tc0(s, ...r); };
  env.L.s = (hz, ...r) => { sounds.push(hz); return s0(hz, ...r); };
  const f = compileGame(env.L, code);
  const I = env.I;
  const frame = (n = 1) => { for (let j = 0; j < n; j++) { I.T++; f(I); I.C = 0; I.A = 0; I.L = 0; I.R = 0; } };
  return { f, I, L: env.L, env, code, frame, texts, sounds, dbg: () => f.dbg() };
}
const kindOf = (g, id) => g.dbg().k[id];
const actors = (g, id) => g.L.all(kindOf(g, id));

test('every template compiles without errors and is valid JavaScript', () => {
  for (const t of api.VTEMPLATES) {
    const { code, errors } = api.vcompile(clone(t.p));
    assert.deepEqual(Array.from(errors), [], t.name);
    assert.doesNotThrow(() => new Function('L', 'with(L){' + code + '\n}'), t.name);
  }
});

